function getRandomQuiz() {
  return quizzes[
    Math.floor(Math.random() * quizzes.length)
  ];
}

module.exports.run = async function ({ api, event }) {
  const { threadID, messageID } = event;

  if (!global.client.handleReply) {
    global.client.handleReply = [];
  }

  const data = getRandomQuiz();

  const msg =
`╭──────────────────╮
      🎯 𝐆𝐊 𝐐𝐔𝐈𝐙
╰──────────────────╯

📚 BCS & Admission Preparation

❓ ${data.q}

🅰️ A › ${data.A}
🅱️ B › ${data.B}
©️ C › ${data.C}
🅳 D › ${data.D}

⏰ সময়: ৩০ সেকেন্ড
✍️ উত্তর দিতে শুধু A / B / C / D লিখুন।

🤖 Tum Dum
👑 Owner: Eram`;

  return api.sendMessage(
    msg,
    threadID,
    (err, info) => {

      if (err) return;

      const timeout = setTimeout(() => {

        const index =
          global.client.handleReply.findIndex(
            item =>
              item.messageID === info.messageID
          );

        if (index === -1) return;

        const quiz =
          global.client.handleReply[index];

        if (!quiz.answered) {

          api.sendMessage(
`⏰ 𝐓𝐈𝐌𝐄 𝐔𝐏!

❌ সময় শেষ হয়ে গেছে।

✅ সঠিক উত্তর: ${quiz.answer}

📖 প্রশ্ন:
${quiz.question}`,
            threadID
          );
        }

        global.client.handleReply.splice(
          index,
          1
        );

      }, TIME_LIMIT);

      global.client.handleReply.push({
        name: module.exports.config.name,
        messageID: info.messageID,
        answer: data.answer,
        question: data.q,
        timeout: timeout,
        answered: false
      });

    },
    messageID
  );
};

module.exports.handleReply = async function ({
  api,
  event,
  handleReply
}) {

  const { threadID, body, messageID } = event;

  if (!body) return;

  const answer =
    body.trim().toUpperCase();

  if (
    !["A", "B", "C", "D"].includes(answer)
  ) {
    return;
  }

  if (handleReply.answered) return;

  handleReply.answered = true;

  clearTimeout(
    handleReply.timeout
  );

  const correct =
    answer === handleReply.answer;

  if (correct) {

    await api.sendMessage(
`╭──────────────────╮
       ✅ 𝐂𝐎𝐑𝐑𝐄𝐂𝐓
╰──────────────────╯

🎉 সঠিক উত্তর দিয়েছো!

🏆 Answer: ${handleReply.answer}
📚 ভালো করেছো!`,
      threadID,
      messageID
    );

  } else {

    await api.sendMessage(
`╭──────────────────╮
        ❌ 𝐖𝐑𝐎𝐍𝐆
╰──────────────────╯

তোমার উত্তর: ${answer}
সঠিক উত্তর: ${handleReply.answer}

📚 আবার চেষ্টা করো।`,
      threadID,
      messageID
    );
  }

  const index =
    global.client.handleReply.findIndex(
      item =>
        item.messageID ===
        handleReply.messageID
    );

  if (index !== -1) {
    global.client.handleReply.splice(
      index,
      1
    );
  }
};
