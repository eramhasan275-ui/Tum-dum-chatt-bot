function random(array) {
  return array[Math.floor(Math.random() * array.length)];
}

function getQuery(body) {
  return body
    .replace(
      /^(baby|bot|bby|jan|xan|জান|বট|বেবি)\s*/i,
      ""
    )
    .trim()
    .toLowerCase();
}

